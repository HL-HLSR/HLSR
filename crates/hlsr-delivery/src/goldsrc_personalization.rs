//! Кастомизация HL1 через Bunnymod XT (`goldsrc-personalization.js`). Прицел и цвет HUD хранятся
//! в тех же полях, что у Ghosting (его `gh_cross_*` повторяют `bxt_cross_*`), поэтому лаунчер
//! переиспользует редактор. Панели BXT, оружие и поле зрения лежат в отдельном поле `bxt`.
//!
//! Пишутся только команды из белого списка правил HL1 на speedrun.com. Каждая пишется явно,
//! даже выключенная: иначе отключённая в лаунчере настройка осталась бы в игре до перезапуска.
//!
//! 0.4.9: строки из [`to_cfg_lines`] лаунчер пишет в файл игрока по одной и только изменённые
//! (`player_config::write_personalization`). Отдельный hlsr-personalization.cfg остаётся снимком для
//! скриптов гайда, которые его вызывают в игре. `apply_to_install` и `ensure_default_userconfig`
//! (путь 0.4.7: файл, строка exec в userconfig.cfg, hlsr-binds.cfg) зовёт только запуск
//! `hlsr-platform`, пока тот не перейдёт на `default_configs::prepare_for_launch` (задача F2l).

