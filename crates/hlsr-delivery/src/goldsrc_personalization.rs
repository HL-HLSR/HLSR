pub const PERSONALIZATION_FILE: &str = "hlsr-personalization.cfg";
pub const EXEC_LINE: &str = "exec hlsr-personalization.cfg";

/// Панели BXT с положением (`bxt_hud_<панель>` и `bxt_hud_<панель>_anchor`).
pub const PANELS: [&str; 4] = ["timer", "speedometer", "jumpspeed", "viewangles"];

/// `defaultBxt()`.
pub fn default_bxt() -> Extras {
    goldsrc_settings::from_flat(&Value::Null).bxt
}

/// `sanitizeBxt(raw)`: все поля BXT с годными значениями или умолчаниями.
pub fn sanitize_bxt(raw: &Value) -> Extras {
    goldsrc_settings::from_extras(&goldsrc_settings::sanitize_extras(raw)).bxt
}

fn flag(value: bool) -> &'static str {
    if value { "1" } else { "0" }
}

fn on(bxt: &Extras, key: &str) -> bool {
    matches!(bxt.get(key), Some(ExtraValue::Bool(true)))
}

/// Число поля в записи JS (`${b.fov}`).
fn number(bxt: &Extras, key: &str) -> String {
    match bxt.get(key) {
        Some(ExtraValue::Number(value)) => number_text(*value),
        other => unreachable!("поле {key} — число, а не {other:?}"),
    }
}

fn number_text(value: f64) -> String {
    js::to_string(&js_number(value))
}

fn percent(bxt: &Extras, key: &str) -> f64 {
    match bxt.get(key) {
        Some(ExtraValue::Number(value)) => *value,
        other => unreachable!("поле {key} — число, а не {other:?}"),
    }
}

/// HUD игры и панели BXT рисуются сложением: картинка + цвет × спрайт. Когда задан свой цвет, BXT
/// подставляет его уже после того, как игра учла прозрачность, и `bxt_hud_game_alpha` ни на что
/// не влияет (проверено в игре). Поэтому прозрачность лаунчер вносит в сам цвет: при сложении
/// цвет × a/255 даёт ровно то же, что прозрачность a.
fn hud_color_of(s: &Personalization) -> String {
    if !s.hud_enabled {
        return String::new();
    }
    if s.hud_alpha <= 0 {
        return color_to_string(s.hud_color);
    }
    let k = f64::from(s.hud_alpha) / 255.0;
    let scaled = |channel: u8| math_round(f64::from(channel) * k) as u8;
    color_to_string(Color {
        r: scaled(s.hud_color.r),
        g: scaled(s.hud_color.g),
        b: scaled(s.hud_color.b),
    })
}

/// `toCfgLines(settings)`: текст `hlsr-personalization.cfg` (CRLF, latin1) для любых настроек
/// игры; в них важны поля `personalization` и `bxt`.
pub fn to_cfg_lines(settings: &Value) -> String {
    let s = sanitize_personalization(prop(settings, "personalization").unwrap_or(&Value::Null));
    let b = sanitize_bxt(prop(settings, "bxt").unwrap_or(&Value::Null));
    let hud_color = hud_color_of(&s);
    let cross_color = if s.hud_enabled && s.hud_affects_crosshair {
        s.hud_color
    } else {
        s.cross_color
    };
    // Штатный прицел скрывает своя настройка прицела BXT, пока тот включён, или отдельный флаг
    // bxt.hideCrosshair: им игра остаётся вовсе без прицела, как с crosshair 0 в cfg игрока.
    let hide_default = on(&b, "hideCrosshair") || (s.cross_enabled && s.cross_hide_default);

    let mut lines: Vec<String> = vec![
        "// Generated by HLSR Launcher. Do not edit: overwritten before every launch.".to_owned(),
        "// Executed from userconfig.cfg.".to_owned(),
        format!("bxt_hud_game_color \"{hud_color}\""),
        "bxt_hud_game_alpha \"0\"".to_owned(),
        format!("bxt_hud_color \"{hud_color}\""),
        format!("crosshair \"{}\"", if hide_default { 0 } else { 1 }),
        format!("bxt_cross \"{}\"", flag(s.cross_enabled)),
        format!("bxt_cross_color \"{}\"", color_to_string(cross_color)),
        format!("bxt_cross_alpha \"{}\"", s.cross_alpha),
        format!("bxt_cross_thickness \"{}\"", s.cross_thickness),
        format!("bxt_cross_size \"{}\"", s.cross_size),
        format!("bxt_cross_gap \"{}\"", s.cross_gap),
        format!(
            "bxt_cross_outline \"{}\"",
            if s.cross_outline {
                s.cross_outline_thickness
            } else {
                0
            }
        ),
        format!("bxt_cross_circle_radius \"{}\"", s.cross_circle_radius),
        format!(
            "bxt_cross_dot_color \"{}\"",
            s.cross_dot_color.map(color_to_string).unwrap_or_default()
        ),
        format!("bxt_cross_dot_size \"{}\"", s.cross_dot_size),
        format!("bxt_cross_top_line \"{}\"", flag(s.cross_top_line)),
        format!("bxt_cross_bottom_line \"{}\"", flag(s.cross_bottom_line)),
        format!("bxt_cross_left_line \"{}\"", flag(s.cross_left_line)),
        format!("bxt_cross_right_line \"{}\"", flag(s.cross_right_line)),
    ];

    for key in PANELS {
        lines.push(format!("bxt_hud_{key} \"{}\"", flag(on(&b, key))));
        lines.push(format!(
            "bxt_hud_{key}_anchor \"{} {}\"",
            number_text(percent(&b, &format!("{key}X")) / 100.0),
            number_text(percent(&b, &format!("{key}Y")) / 100.0)
        ));
    }

    lines.extend([
        format!("bxt_hud_jumpdistance \"{}\"", flag(on(&b, "jumpdistance"))),
        format!("bxt_hud_precision \"{}\"", number(&b, "precision")),
        format!(
            "bxt_hud_incorrect_fps_indicator \"{}\"",
            flag(on(&b, "incorrectFps"))
        ),
        format!("default_fov \"{}\"", number(&b, "fov")),
        format!(
            "bxt_fix_widescreen_fov \"{}\"",
            flag(on(&b, "fixWidescreenFov"))
        ),
        format!("bxt_viewmodel_fov \"{}\"", number(&b, "viewmodelFov")),
        format!(
            "bxt_viewmodel_semitransparent \"{}\"",
            flag(on(&b, "viewmodelSemitransparent"))
        ),
        format!(
            "bxt_remove_viewmodel \"{}\"",
            flag(on(&b, "removeViewmodel"))
        ),
        format!(
            "bxt_viewmodel_ofs_forward \"{}\"",
            number(&b, "viewmodelForward")
        ),
        format!(
            "bxt_viewmodel_ofs_right \"{}\"",
            number(&b, "viewmodelRight")
        ),
        format!("bxt_viewmodel_ofs_up \"{}\"", number(&b, "viewmodelUp")),
        format!(
            "bxt_viewmodel_bob_angled \"{}\"",
            flag(on(&b, "viewmodelBobAngled"))
        ),
        format!(
            "bxt_viewmodel_disable_idle \"{}\"",
            flag(on(&b, "viewmodelNoIdle"))
        ),
        format!(
            "bxt_viewmodel_disable_equip \"{}\"",
            flag(on(&b, "viewmodelNoEquip"))
        ),
        String::new(),
    ]);
    lines.join("\r\n")
}

/// Итог [`apply_to_install`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Applied {
    /// Не GoldSrc или нет папки игры (`{ status: "skipped" }`).
    Skipped,
    /// `{ status: "applied", file, bindsFile, appended }`: `appended` — в userconfig.cfg
    /// добавлена хотя бы одна строка exec лаунчера.
    Applied {
        file: PathBuf,
        binds_file: Option<PathBuf>,
        appended: bool,
    },
}

/// `applyToInstall(installPath, config, settings)` для настроек запуска игры.
pub fn apply_to_install(
    search: &CfgSearch,
    install_path: &Path,
    config: &LaunchConfig,
    settings: &Value,
) -> Result<Applied, Failure> {
    apply_to(
        search,
        install_path,
        config.game_directory,
        config.engine,
        settings,
    )
}

/// То же по папке игры и движку из настроек запуска. Пишет hlsr-personalization.cfg и
/// hlsr-binds.cfg, подключает их строками exec в userconfig.cfg (после стандартного
/// userconfig.cfg лаунчера, если стоял стоковый) и обновляет хвост импортированного конфига.
pub fn apply_to(
    search: &CfgSearch,
    install_path: &Path,
    game_directory: &str,
    engine: Option<&str>,
    settings: &Value,
) -> Result<Applied, Failure> {
    if game_directory.is_empty() || engine != Some("goldsrc") {
        return Ok(Applied::Skipped);
    }
    node_fs::mkdir_recursive(&cfg_search::mod_dir_of(
        install_path,
        game_directory,
        "goldsrc",
    )?)?;
    ensure_default_userconfig(search, install_path, game_directory)?;
    // Файлы ищутся так же, как в игре: сначала valve_WON_<язык>.
    let files = search.files_of(
        install_path,
        game_directory,
        "goldsrc",
        LanguageOption::Detect,
    )?;
    let file = files.path_of(PERSONALIZATION_FILE);
    node_fs::write_text(&file, &to_cfg_lines(settings), Encoding::Latin1)?;
    let appended = game_binds_install::ensure_exec_line(
        &files.path_of("userconfig.cfg"),
        EXEC_LINE,
        Encoding::Latin1,
    )?;
    // Переназначения клавиш подключаются после настроек BXT: строка exec добавляется позже,
    // поэтому и в userconfig.cfg стоит ниже.
    let binds = game_binds_install::apply_binds(
        search,
        install_path,
        "hl1-won",
        game_directory,
        prop(settings, "binds").unwrap_or(&Value::Null),
    )?;
    game_binds_install::sync_import_trailer(search, install_path, "hl1-won", game_directory)?;
    let (binds_file, binds_appended) = match binds {
        ApplyBinds::Applied { file, appended } => (Some(file), appended),
        ApplyBinds::Skipped => (None, false),
    };
    Ok(Applied::Applied {
        file,
        binds_file,
        appended: appended || binds_appended,
    })
}

/// Ставит стандартный userconfig.cfg лаунчера вместо отсутствующего, стокового из пакета или
/// стандартного прошлой версии (как стандартный autoexec Ghosting). Свой userconfig игрока не
/// трогает. Строки exec лаунчера переносятся в конец. `true` — файл записан.
pub fn ensure_default_userconfig(
    search: &CfgSearch,
    install_path: &Path,
    game_directory: &str,
) -> Result<bool, Failure> {
    let files = search.files_of(
        install_path,
        game_directory,
        "goldsrc",
        LanguageOption::Detect,
    )?;
    let file = files.path_of("userconfig.cfg");
    let text = node_fs::read_text_optional(&file, Encoding::Latin1)?;
    let normalized = text.as_ref().map(|text| text.replace("\r\n", "\n"));
    let lines: Vec<&str> = normalized
        .as_deref()
        .map(|text| text.split('\n').collect())
        .unwrap_or_default();
    let exec_lines: Vec<&str> = lines
        .iter()
        .map(|line| js::trim(line))
        .filter(|line| is_launcher_exec(line))
        .collect();
    if text.is_some() {
        let own: Vec<&str> = lines
            .iter()
            .copied()
            .filter(|line| !is_launcher_exec(js::trim(line)))
            .collect();
        let own = own.join("\n");
        let own = own.trim_end_matches(is_whitespace);
        let hash = hex(&Sha256::digest(js::latin1_bytes(own)));
        if !hl1_default_userconfig::REPLACEABLE_SHA256.contains(&hash.as_str()) {
            return Ok(false);
        }
    }
    if let Some(parent) = file.parent() {
        node_fs::mkdir_recursive(parent)?;
    }
    let mut body = hl1_default_userconfig::text().to_owned();
    for line in exec_lines {
        body.push_str(line);
        body.push_str("\r\n");
    }
    node_fs::write_text(&file, &body, Encoding::Utf8)?;
    Ok(true)
}
