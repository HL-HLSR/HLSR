/// SVG значка `name` (квадрат, контур по центру); нет такого — `None`.
pub fn svg(name: &str) -> Option<&'static [u8]> {
    static SVGS: LazyLock<HashMap<&'static str, Vec<u8>>> = LazyLock::new(|| {
        PATHS
            .iter()
            .map(|(name, width, path)| {
                // Квадрат со стороной по большей стороне контура, контур по центру (`meet`).
                let side = (*width).max(512);
                let left = (side - *width) as f32 / -2.;
                let top = (side - 512) as f32 / -2.;
                let svg = format!(
                    "<svg xmlns='http://www.w3.org/2000/svg' width='{side}' height='{side}' \
                     viewBox='{left} {top} {side} {side}'><path fill='#fff' d='{path}'/></svg>"
                );
                (*name, svg.into_bytes())
            })
            .collect()
    });
    SVGS.get(name).map(Vec::as_slice)
}

