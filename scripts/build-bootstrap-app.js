  "src/main/uninstall/launcher-uninstall.js",
  "src/main/linux/library-cleanup.js",
  "src/shared/library-path.js",
  "src/shared/links.js",
  "src/main/linux/DesktopIntegration.js",
  "src/main/game-delivery/manifest-signing.js",
