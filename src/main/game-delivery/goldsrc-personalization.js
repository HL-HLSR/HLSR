"use strict";

const personalization = require("./ghosting-personalization");
const goldsrcSettings = require("../../shared/goldsrc-settings");

// Кастомизация HL1 через Bunnymod XT. Прицел и цвет HUD хранятся в тех же
// полях, что у Ghosting (его gh_cross_* повторяют bxt_cross_*), поэтому
// лаунчер переиспользует редактор. Панели BXT, оружие и поле зрения лежат в
// отдельном поле bxt.
//
// Пишутся только команды из белого списка правил HL1 на speedrun.com. Каждая
// пишется явно, даже выключенная: иначе отключённая в лаунчере настройка
// осталась бы в игре до перезапуска.
//
// Строки из toCfgLines лаунчер пишет в файл игрока по одной и только изменённые
// (player-config.js, writePersonalization). Отдельный hlsr-personalization.cfg
// остаётся снимком для скриптов гайда, которые его вызывают в игре.

const PERSONALIZATION_FILE = "hlsr-personalization.cfg";
const EXEC_LINE = `exec ${PERSONALIZATION_FILE}`;

const PANELS = ["timer", "speedometer", "jumpspeed", "viewangles"];

function defaultBxt() {
  return goldsrcSettings.fromFlat({}).bxt;
}

function sanitizeBxt(raw) {
  return goldsrcSettings.fromFlat(goldsrcSettings.sanitizeExtras(raw)).bxt;
}

const flag = (value) => (value ? "1" : "0");
const rgb = personalization.colorToString;

// HUD игры и панели BXT рисуются сложением: картинка + цвет × спрайт. Когда
// задан свой цвет, BXT подставляет его уже после того, как игра учла
// прозрачность, и bxt_hud_game_alpha ни на что не влияет (проверено в игре).
// Поэтому прозрачность лаунчер вносит в сам цвет: при сложении цвет × a/255
// даёт ровно то же, что прозрачность a.
function hudColorOf(s) {
  if (!s.hudEnabled) return "";
  if (!(s.hudAlpha > 0)) return rgb(s.hudColor);
  const k = s.hudAlpha / 255;
  return rgb({ r: Math.round(s.hudColor.r * k), g: Math.round(s.hudColor.g * k), b: Math.round(s.hudColor.b * k) });
}

function toCfgLines(settings) {
  const s = personalization.sanitizePersonalization(settings && settings.personalization);
  const b = sanitizeBxt(settings && settings.bxt);
  const hudColor = hudColorOf(s);
  const crossColor = s.hudEnabled && s.hudAffectsCrosshair ? s.hudColor : s.crossColor;
  // Штатный прицел скрывает своя настройка прицела BXT, пока тот включён,
  // или отдельный флаг bxt.hideCrosshair: им игра остаётся вовсе без
  // прицела, как с crosshair 0 в cfg игрока.
  const hideDefault = b.hideCrosshair || (s.crossEnabled && s.crossHideDefault);

  const lines = [
    "// Generated by HLSR Launcher. Do not edit: overwritten before every launch.",
    "// Executed from userconfig.cfg.",
    `bxt_hud_game_color "${hudColor}"`,
    `bxt_hud_game_alpha "0"`,
    `bxt_hud_color "${hudColor}"`,
    `crosshair "${hideDefault ? 0 : 1}"`,
    `bxt_cross "${flag(s.crossEnabled)}"`,
    `bxt_cross_color "${rgb(crossColor)}"`,
    `bxt_cross_alpha "${s.crossAlpha}"`,
    `bxt_cross_thickness "${s.crossThickness}"`,
    `bxt_cross_size "${s.crossSize}"`,
    `bxt_cross_gap "${s.crossGap}"`,
    `bxt_cross_outline "${s.crossOutline ? s.crossOutlineThickness : 0}"`,
    `bxt_cross_circle_radius "${s.crossCircleRadius}"`,
    `bxt_cross_dot_color "${s.crossDotColor ? rgb(s.crossDotColor) : ""}"`,
    `bxt_cross_dot_size "${s.crossDotSize}"`,
    `bxt_cross_top_line "${flag(s.crossTopLine)}"`,
    `bxt_cross_bottom_line "${flag(s.crossBottomLine)}"`,
    `bxt_cross_left_line "${flag(s.crossLeftLine)}"`,
    `bxt_cross_right_line "${flag(s.crossRightLine)}"`,
  ];

  for (const key of PANELS) {
    lines.push(
      `bxt_hud_${key} "${flag(b[key])}"`,
      `bxt_hud_${key}_anchor "${b[key + "X"] / 100} ${b[key + "Y"] / 100}"`
    );
  }

  lines.push(
    `bxt_hud_jumpdistance "${flag(b.jumpdistance)}"`,
    `bxt_hud_precision "${b.precision}"`,
    `bxt_hud_incorrect_fps_indicator "${flag(b.incorrectFps)}"`,
    `default_fov "${b.fov}"`,
    `bxt_fix_widescreen_fov "${flag(b.fixWidescreenFov)}"`,
    `bxt_viewmodel_fov "${b.viewmodelFov}"`,
    `bxt_viewmodel_semitransparent "${flag(b.viewmodelSemitransparent)}"`,
    `bxt_remove_viewmodel "${flag(b.removeViewmodel)}"`,
    `bxt_viewmodel_ofs_forward "${b.viewmodelForward}"`,
    `bxt_viewmodel_ofs_right "${b.viewmodelRight}"`,
    `bxt_viewmodel_ofs_up "${b.viewmodelUp}"`,
    `bxt_viewmodel_bob_angled "${flag(b.viewmodelBobAngled)}"`,
    `bxt_viewmodel_disable_idle "${flag(b.viewmodelNoIdle)}"`,
    `bxt_viewmodel_disable_equip "${flag(b.viewmodelNoEquip)}"`,
    ""
  );
  return lines.join("\r\n");
}

module.exports = {
  PERSONALIZATION_FILE,
  EXEC_LINE,
  PANELS,
  defaultBxt,
  sanitizeBxt,
  toCfgLines,
};
