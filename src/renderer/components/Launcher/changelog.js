function notNewerThan(a, b) {
  const parse = (value) =>
    String(value || "0")
      .split("-")[0]
      .split(".")
      .map((part) => parseInt(part, 10) || 0);

  const left = parse(a);
  const right = parse(b);

  for (let i = 0; i < Math.max(left.length, right.length); i++) {
    const l = left[i] || 0;
    const r = right[i] || 0;
    if (l !== r) return l < r;
  }

  return true;
}

function toText(raw) {
  return String(raw || "")
    .replace(/<[^>]*>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, " ")
    .trim();
}

function versionOf(headingText) {
  const match = headingText.match(/\[\s*v\.?\s*([0-9]+(?:\.[0-9]+)*)\s*\]/i);
  return match ? match[1] : null;
}

function parseLegacy(html) {
  const source = String(html || "");
  const releases = [];

  const tokenRe = /<(h4|h3|li)[^>]*>([\s\S]*?)<\/\1>/gi;
  let match;
  let release = null;
  let group = null;

  const startGroup = (title) => {
    group = { title: title || null, items: [] };
    if (release) release.groups.push(group);
  };

  while ((match = tokenRe.exec(source)) !== null) {
    const tag = match[1].toLowerCase();
    const text = toText(match[2]);
    if (!text) continue;

    if (tag === "h4") {
      release = { version: versionOf(text), title: text, groups: [] };
      releases.push(release);
      group = null;
      continue;
    }

    if (!release) continue;

    if (tag === "h3") {
      startGroup(text);
      continue;
    }

    if (!group) startGroup(null);
    group.items.push(text);
  }

  return releases.filter((item) => item.groups.some((g) => g.items.length));
}

function buildChangelog(legacyHtml, language, version) {
  const lang = language === "en" ? "en" : "ru";

  const structured = RELEASES.filter((release) => notNewerThan(release.version, version)).map(
    (release, index) => ({
      version: release.version,
      title: `${CURRENT_TITLE[lang]} ${release.version}`.trim(),
      groups: [{ title: null, items: release[lang].slice() }],
      current: index === 0,
    })
  );

  return structured.concat(parseLegacy(legacyHtml));
}

